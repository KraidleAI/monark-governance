#!/usr/bin/env node
// scripts/emit-u4b-calibration.mjs - U-4b-2b (ADR-U4b-2b D1; G0 U-4b-2 2b-2, decision N-7): the EMITTER of the
// liquidation-eligible-coverage block of apps/harness/src/calibration.ts. It reads the OUTPUT of the frozen generator
// scripts/record-u4b-calib.mjs (`buildRegistryEntries`, unmodified, sha pinned by ADR-U4b D4) over the committed fresh
// scores series, and writes that output as TypeScript: the cell-A predictor BASE (meta.cell_a.predictor_id), one scores
// array + pinned C5 digest + provenance per COMMITTABLE stratum, and the list of committed entries. It FILTERS NOTHING:
// every stratum the generator marks committable (under_calib false) is emitted with its scores as generated, in
// generator order (a q-hat of 0, a zero score, a duplicate: all kept); the strata the generator marks under_calib are
// the ones the registry does not hold (checkpoint-1 C-4). Hand transcription of 170 scores is exactly the risk this
// tool removes (checkpoint-1 G0 Q-3).
//
//   node scripts/emit-u4b-calibration.mjs --scores <U4b-scores-EP.jsonl> --book <U4b-book-B0.json>
//     --oracle-path <U4b-oracle-path-EP.jsonl> --labels <U3-realized-EP.jsonl> --report <apps/site/data/ukemi-course.json>
//     --measured-on <YYYY-MM-DD> [--write <calibration.ts> | --check <calibration.ts>]
//
// Without --write/--check it prints the block. --write replaces the region between the two marker lines (inclusive)
// of the target file; --check exits 1 if that region differs from what it would write (no write). Every input is a
// committed repository file, so the block is recomposable in the repository (test u4b_committed_registry_equals_
// generator_output). The provenance it composes is English ASCII with NO reader path, NO amount and NO price (it is
// exported with calibration.ts, checkpoint-1 C-7): counts, digests, identifiers and tool names only. No network, no
// clock. The agent does not commit (R-20).
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import { calibDigest } from "@monark/contracts";
import { buildRegistryEntries } from "./record-u4b-calib.mjs";
import { canonicalJson } from "../apps/site/lib/ukemi-course-load.ts";

export const BEGIN_MARK = "// ---- BEGIN GENERATED by scripts/emit-u4b-calibration.mjs from the frozen generator scripts/record-u4b-calib.mjs; never hand-edit ----";
export const END_MARK = "// ---- END GENERATED by scripts/emit-u4b-calibration.mjs ----";
const PER_LINE = 8;

const sha256 = (buf) => createHash("sha256").update(buf).digest("hex");
const lfSha = (path) => sha256(Buffer.from(readFileSync(path, "utf8").replace(/\r\n/g, "\n"), "utf8"));

/** The scores series as the frozen generator's own main() reads it: its meta line and its class-A rows. */
export function readScores(path) {
  const lines = readFileSync(path, "utf8").split(/\r?\n/).filter((l) => l.trim()).map((l) => JSON.parse(l));
  const meta = lines.find((l) => l.kind === "meta");
  if (meta === undefined) throw new Error("emit-u4b-calibration: the scores series has no meta line");
  return { meta, rowsA: lines.filter((r) => r.kind === "score_a") };
}

/** Smallest n whose conformal rank ceil((n+1)(1-alpha)) is BELOW n (an interior q-hat), alpha = 1/den exactly. */
export function interiorRankMinN(alpha) {
  const den = Math.round(1 / alpha);
  if (Math.abs(1 / den - alpha) > 1e-15) throw new Error(`emit-u4b-calibration: alpha ${String(alpha)} is not 1/k`);
  for (let n = 1; ; n++) if (Math.ceil(((n + 1) * (den - 1)) / den) < n) return n;
}

const upper = (k) => `S${String(k)}`;
const hex = (v, what) => { if (typeof v !== "string" || !/^[0-9a-f]{64}$/.test(v)) throw new Error(`emit-u4b-calibration: ${what} is not 64 lowercase hex`); return v; };

/**
 * PURE: generator entries (+ the digests of the committed inputs) -> the TypeScript block, markers included. Throws on
 * any inconsistency (a non-committable stratum without under_calib, a digest that is not the C5 of its scores, a
 * non-ASCII provenance) rather than emitting a doubtful block.
 */
export function emitBlock({ entries, predictorBase, digests, measuredOn }) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(measuredOn)) throw new Error("emit-u4b-calibration: --measured-on must be YYYY-MM-DD");
  const committed = entries.filter((e) => !e.under_calib);
  const abstaining = entries.filter((e) => e.under_calib);
  if (committed.length === 0) throw new Error("emit-u4b-calibration: the generator marks no stratum committable; nothing to commit");
  const out = [BEGIN_MARK];
  out.push(`// Input: the fresh scores series (sha256 LF ${digests.scores}); ${String(committed.length)} of ${String(entries.length)} strata committable.`);
  out.push("/** The committed cell-A predictor BASE of the liquidation-eligible-coverage class: the fresh episode's scores meta");
  out.push(" *  cell_a.predictor_id (ADR-U4b-2b D1). The served lookup key is `${UKEMI_LIQ_PREDICTOR_BASE}/s${strateOf(yhat)}`,");
  out.push(" *  re-derived SERVER-SIDE (the client predictor_id is ignored for this class). */");
  out.push(`export const UKEMI_LIQ_PREDICTOR_BASE = ${JSON.stringify(predictorBase)};`);
  const names = [];
  for (const e of committed) {
    if (e.task_class !== "liquidation-eligible-coverage") throw new Error(`emit-u4b-calibration: unexpected task_class ${String(e.task_class)}`);
    if (e.predictor_id !== `${predictorBase}/s${String(e.strate)}`) throw new Error(`emit-u4b-calibration: stratum ${String(e.strate)} key is not BASE/s<k>`);
    if (e.scale !== "1") throw new Error("emit-u4b-calibration: only scale 1 is committed (ADR-U4b-2b D1; G0 D-8: scale > 1 is a STOP)");
    if (calibDigest(e.scores) !== e.calib_digest) throw new Error(`emit-u4b-calibration: stratum ${String(e.strate)} calib_digest is not the C5 of its scores`);
    if (e.scores.length !== e.n) throw new Error(`emit-u4b-calibration: stratum ${String(e.strate)} n differs from its scores`);
    const nInterior = interiorRankMinN(e.alpha);
    const qhatWords = e.p === e.n
      ? `quantile rank p=${String(e.p)}, equal to n, so q_hat is the stratum maximum (n below ${String(nInterior)}, pre-registered H-2bis, reported as is)`
      : `quantile rank p=${String(e.p)}, below n (an interior q_hat, n at least ${String(nInterior)})`;
    const ks = abstaining.map((x) => `s${String(x.strate)}`);
    const others = ks.length === 0
      ? "every stratum of the class is committed"
      : ks.length === 1
        ? `stratum ${ks[0]} is not committed (n below nMin ${String(e.n_min)}: under_calib)`
        : `strata ${ks.slice(0, -1).join(", ")} and ${ks[ks.length - 1]} are not committed (n below nMin ${String(e.n_min)}: under_calib)`;
    const provenance =
      `measured -- Ukemi liquidation-eligible-coverage class A, stratum s${String(e.strate)} of the fresh episode ` +
      `${digests.eventId} (Aave v3 core liquidations with WETH collateral; one recorded episode): n=${String(e.n)} ` +
      `one-sided exceedance scores max(Y - yhat, 0) at scale 1; alpha=${String(e.alpha)}, nMin=${String(e.n_min)}; ${qhatWords}; ` +
      `calib_digest=${e.calib_digest}; ${others}; scores series sha256 ${digests.scores}, book sha256 ${digests.book}, ` +
      `oracle path sha256 ${digests.oracle}, realized labels sha256 ${digests.labels} (LF); hypothesis report body_digest ` +
      `${digests.reportBody}; frozen generator scripts/record-u4b-calib.mjs, emitted by scripts/emit-u4b-calibration.mjs; ` +
      `measured ${measuredOn}.`;
    if (!/^[\x20-\x7e]+$/.test(provenance)) throw new Error("emit-u4b-calibration: the provenance must be printable ASCII (exported text)");
    const S = upper(e.strate);
    out.push("");
    out.push(`/** Stratum s${String(e.strate)}: the ${String(e.n)} committed one-sided exceedance scores max(Y - yhat, 0), base 8-dec at scale 1,`);
    out.push(" *  in generator order (ascending). Order-independent for the digest (calibDigest sorts). */");
    out.push(`export const UKEMI_LIQ_${S}_CALIB: readonly number[] = [`);
    for (let i = 0; i < e.scores.length; i += PER_LINE) out.push(`  ${e.scores.slice(i, i + PER_LINE).map((v) => String(v)).join(", ")},`);
    out.push("];");
    out.push(`/** Committed C5 digest of stratum s${String(e.strate)} (ADR-M001 C5, float64_be sorted): the value the wire verdict carries. */`);
    out.push(`export const UKEMI_LIQ_${S}_CALIB_DIGEST_PINNED = ${JSON.stringify(e.calib_digest)};`);
    out.push(`/** Measured provenance of stratum s${String(e.strate)} (English ASCII, exported: no reader path, no amount, no price). */`);
    out.push(`export const UKEMI_LIQ_${S}_CALIB_PROVENANCE =`);
    out.push(`  ${JSON.stringify(provenance)};`);
    names.push({ S, key: e.predictor_id });
  }
  out.push("");
  out.push("/** The committed strata of the class: EXACTLY the committable strata of the frozen generator, in its order; every");
  out.push(" *  other stratum is absent, so the served gate abstains under_calib there (checkpoint-1 C-4). */");
  out.push("export const UKEMI_LIQ_COMMITTED: readonly CommittedCalibration[] = [");
  for (const { S, key } of names) {
    out.push("  {");
    out.push(`    taskClass: "liquidation-eligible-coverage",`);
    out.push(`    predictorId: ${JSON.stringify(key)},`);
    out.push(`    scores: UKEMI_LIQ_${S}_CALIB,`);
    out.push(`    digestPinned: UKEMI_LIQ_${S}_CALIB_DIGEST_PINNED,`);
    out.push(`    provenance: UKEMI_LIQ_${S}_CALIB_PROVENANCE,`);
    out.push("  },");
  }
  out.push("];");
  out.push(END_MARK);
  return out.join("\n") + "\n";
}

/** Read every input, cross-check the report copy against the committed series, and compose the block. */
export function blockFromFiles({ scores, book, oraclePath, labels, report, measuredOn }) {
  const { meta, rowsA } = readScores(scores);
  const predictorBase = meta.cell_a?.predictor_id;
  if (typeof predictorBase !== "string" || predictorBase.length === 0) throw new Error("emit-u4b-calibration: meta.cell_a.predictor_id is missing");
  const entries = buildRegistryEntries(rowsA, { scale: 1n, predictorBase });
  const rep = JSON.parse(readFileSync(report, "utf8"));
  const bodyDigest = hex(rep.body_digest, "report body_digest");
  if (sha256(Buffer.from(canonicalJson(rep.body), "utf8")) !== bodyDigest) throw new Error("emit-u4b-calibration: the report body_digest is not the sha256 of its canonical body");
  const digests = { scores: lfSha(scores), book: lfSha(book), oracle: lfSha(oraclePath), labels: lfSha(labels), reportBody: bodyDigest, eventId: String(rep.body.event_id) };
  const inputs = rep.provenance?.inputs ?? {};
  for (const [role, got] of [["scores", digests.scores], ["oracle_path", digests.oracle], ["u3_realized", digests.labels]]) {
    if (hex(inputs[role]?.sha256_lf, `report input ${role}`) !== got) throw new Error(`emit-u4b-calibration: the report was produced on another ${role} (report ${String(inputs[role]?.sha256_lf)}, committed ${got})`);
  }
  if (!predictorBase.includes(`/${digests.eventId}/`)) throw new Error("emit-u4b-calibration: the cell-A key does not name the report's episode");
  return emitBlock({ entries, predictorBase, digests, measuredOn });
}

/** Replace the marked region (inclusive) of `text` by `block`; exactly one BEGIN and one END marker must exist. */
export function spliceBlock(text, block) {
  const lf = text.replace(/\r\n/g, "\n");
  const i = lf.indexOf(BEGIN_MARK), j = lf.indexOf(END_MARK);
  if (i < 0 || j < i || lf.indexOf(BEGIN_MARK, i + 1) >= 0 || lf.indexOf(END_MARK, j + 1) >= 0) throw new Error("emit-u4b-calibration: the target must carry exactly one BEGIN and one END marker, in order");
  return lf.slice(0, i) + block + lf.slice(j + END_MARK.length + 1);
}

function main() {
  const argv = process.argv.slice(2);
  const arg = (k) => { const i = argv.indexOf(k); return i >= 0 ? argv[i + 1] : undefined; };
  const req = (k) => { const v = arg(k); if (v === undefined) throw new Error(`emit-u4b-calibration: ${k} is REQUIRED (no default input)`); return v; };
  const block = blockFromFiles({ scores: req("--scores"), book: req("--book"), oraclePath: req("--oracle-path"), labels: req("--labels"), report: req("--report"), measuredOn: req("--measured-on") });
  const write = arg("--write"), check = arg("--check");
  if (write !== undefined) {
    writeFileSync(write, spliceBlock(readFileSync(write, "utf8"), block));
    process.stdout.write(`emit-u4b-calibration: block written into ${write} (sha256 of the block ${sha256(Buffer.from(block, "utf8"))})\n`);
  } else if (check !== undefined) {
    const now = readFileSync(check, "utf8").replace(/\r\n/g, "\n");
    if (spliceBlock(now, block) !== now) { process.stderr.write(`emit-u4b-calibration: ${check} differs from the emitted block\n`); process.exitCode = 1; return; }
    process.stdout.write(`emit-u4b-calibration: ${check} carries the emitted block (sha256 ${sha256(Buffer.from(block, "utf8"))})\n`);
  } else {
    process.stdout.write(block);
  }
}
if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) main();
